"""Blind grader for Control R1 fold 2 (INV-6). Scores every arm from hash-labelled prediction files; the arm
labels stay hashed until the table is final, then are revealed and the pre-registered decision rule applied.

    grade_control.py [--out docs/tests/control_r1_2026-10-15.md]
"""
import argparse
import json
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from nhl_sim.control import engine as E  # noqa: E402

RES = Path("results/control_r1")
FROZEN = Path("docs/models/control/r1_frozen_params.json")
ORDER = ["A0", "A1", "A2", "A3", "A4"]
NB, SEED = 2000, 12345
TOTK = np.arange(11)


def load():
    g = pd.read_parquet(RES / "fold2_games.parquet")
    arms = {}
    for f in sorted(RES.glob("fold2_*.npz")):
        z = np.load(f)
        arms[f.stem.split("_")[1]] = {k: z[k] for k in z.files}
    return g, arms


def total_pmf(F):
    G = F.shape[0]
    t = np.zeros((G, 2 * E.N))
    for h in range(E.N):
        for a in range(E.N):
            t[:, h + a] += F[:, h, a]
    out = t[:, :11].copy()
    out[:, 10] = t[:, 10:].sum(1)
    return out


def marg(F):
    return F.sum(2), F.sum(1)   # home-goal pmf, away-goal pmf


def moments(F):
    x = np.arange(E.N)
    ph, pa = marg(F.astype(np.float64))
    mh, ma = ph @ x, pa @ x
    eh2, ea2 = ph @ x**2, pa @ x**2
    eha = np.einsum("gha,h,a->g", F.astype(np.float64), x, x)
    return mh, ma, eh2, ea2, eha


def pooled(F):
    mh, ma, eh2, ea2, eha = moments(F)
    th = lambda v: v.mean()  # noqa: E731
    vh, va = th(eh2) - th(mh) ** 2, th(ea2) - th(ma) ** 2
    cov = th(eha) - th(mh) * th(ma)
    tot_var = vh + va + 2 * cov
    mar_var = vh + va - 2 * cov
    corr = cov / np.sqrt(vh * va)
    # decomposition: variance of per-game means (accuracy / spread) vs mean within-game variance (dispersion)
    within_t = (eh2 - mh**2) + (ea2 - ma**2) + 2 * (eha - mh * ma)
    within_m = (eh2 - mh**2) + (ea2 - ma**2) - 2 * (eha - mh * ma)
    return dict(total_mean=th(mh + ma), margin_mean=th(mh - ma), total_sd=np.sqrt(tot_var), margin_sd=np.sqrt(mar_var),
                corr=corr, total_sd_means=np.std(mh + ma), total_sd_within=np.sqrt(within_t.mean()),
                margin_sd_means=np.std(mh - ma), margin_sd_within=np.sqrt(within_m.mean()))


def rps(pk, actual_k):
    cdf = np.cumsum(pk, 1)
    obs = (actual_k[:, None] <= np.arange(11)[None, :]).astype(float)
    return (((cdf - obs) ** 2)[:, :-1].sum(1) / 10.0)


def boot_idx(n):
    return np.random.default_rng(SEED).integers(0, n, size=(NB, n))


def ci(x, idx):
    m = x[idx].mean(1)
    return x.mean(), np.percentile(m, 2.5), np.percentile(m, 97.5)


def md(df, floatfmt=".4f"):
    return df.to_markdown(floatfmt=floatfmt)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="docs/tests/control_r1_2026-10-15.md")
    args = ap.parse_args()
    g, arms = load()
    hg, ag = g.hg.to_numpy(), g.ag.to_numpy()
    n = len(g)
    idx = boot_idx(n)
    tot_a = np.minimum(hg + ag, 10)
    act = dict(total_mean=(hg + ag).mean(), margin_mean=(hg - ag).mean(), total_sd=(hg + ag).std(), margin_sd=(hg - ag).std(),
               corr=np.corrcoef(hg, ag)[0, 1], reg_tie=(g.end_state != "REG").mean(), home_win=g.home_win.mean())
    ls = {h: E.logscore(a["final"].astype(np.float64), hg, ag) for h, a in arms.items()}
    rows, sec = [], {}
    for h, a in arms.items():
        F = a["final"].astype(np.float64)
        m, lo, hi = ci(ls[h], idx)
        brier = ((a["pwin"] - g.home_win.to_numpy()) ** 2).mean()
        tp = total_pmf(F)
        P = pooled(F)
        sec[h] = dict(tp=tp, P=P, brier=brier, rps=rps(tp, tot_a).mean(), reg_tie=a["reg_tie"].mean())
        rows.append({"arm(hash)": h, "mean_logscore": m, "boot95_lo": lo, "boot95_hi": hi, "ML_Brier": brier,
                     "RPS_total": sec[h]["rps"], "total_SD": P["total_sd"], "margin_SD": P["margin_sd"],
                     "score_corr": P["corr"], "reg_tie": sec[h]["reg_tie"]})
    T = pd.DataFrame(rows).set_index("arm(hash)")
    L = ["# Control R1 results, fold 2 (train through 2023-24, test 2024-25, n=%d games)" % n, "",
         "Generated by `scripts/grade_control.py`. All arms are 'oracle goalie' where they use the goalie term (A1-A4). Metrics are analytic (exact pmf on an 18x18 grid), not sampled.", "",
         f"Actual fold 2: total mean {act['total_mean']:.3f}, total SD {act['total_sd']:.3f}, margin SD {act['margin_sd']:.3f}, score corr {act['corr']:.3f}, regulation-tie rate {act['reg_tie']:.4f}, home win {act['home_win']:.4f}.", "",
         "## Blind table (labels hashed)", "", md(T, ".5f"), "", "TABLE FINAL -- labels revealed below; nothing after this point changes a number above.", ""]
    lab = json.loads((RES / "labels_sealed.json").read_text())
    inv = {v: k for k, v in lab.items()}
    byarm = {inv[h]: h for h in arms}
    L += ["## Label reveal", "", md(pd.DataFrame({"arm": ORDER, "hash": [byarm[a] for a in ORDER]}).set_index("arm")), ""]

    fz = json.loads(FROZEN.read_text())
    # ---- seed floor: 4 seed-offset reruns, 10,000 seeds per game, simulated estimate of the mean log score
    t0 = time.time()
    print("seed floor start", time.strftime("%H:%M:%S"), flush=True)
    seedsd = {}
    seedmeans = {}
    for arm in ORDER:
        a = arms[byarm[arm]]
        par = {"lambda3": fz["lambda3"], "phi": fz["phi_A3"] if arm == "A3" else fz.get("phi_A4")}
        ms = []
        for off in range(4):
            h, aw, es, hw = E.sample_final(arm, a["lam_h"], a["lam_a"], g.q_ot.to_numpy(), g.p_home_tie.to_numpy(), par, 10000, 777 + off)
            cell = np.minimum(h, E.N - 1) * E.N + np.minimum(aw, E.N - 1)
            tgt = np.minimum(hg, E.N - 1) * E.N + np.minimum(ag, E.N - 1)
            cnt = (cell == tgt[:, None]).sum(1)
            ms.append(np.log((cnt + 0.5) / (10000 + 0.5 * E.N * E.N)).mean())
        seedmeans[arm] = ms
        seedsd[arm] = float(np.std(ms, ddof=1))
    print("seed floor done", f"{time.time()-t0:.0f}s", flush=True)
    L += ["## Noise floor", "", f"Paired game bootstrap: {NB} resamples (seed {SEED}). Seed floor: 4 seed-offset reruns of each arm with 10,000 simulated seeds per game; the simulated estimate of the mean log score is smoothed (add 0.5 per cell) and is NOT the decision metric (the primary metric is analytic, so its seed SD is exactly 0); the SD of the 4 estimates is reported and the threshold is max(that SD, 0.001).", "",
          md(pd.DataFrame({"sim_estimates(4 offsets)": {a: ", ".join(f"{x:.5f}" for x in seedmeans[a]) for a in ORDER}, "seed_SD": seedsd}), ".6f"), ""]

    # ---- pairwise and decision
    pm = {a: ls[byarm[a]] for a in ORDER}
    pair = []
    def beats(j, i):
        d = pm[j] - pm[i]
        m, lo, hi = ci(d, idx)
        thr = max(seedsd[j], 0.001)
        return (lo > 0 and m > thr), m, lo, hi, thr
    for j in ORDER:
        for i in ORDER[:ORDER.index(j)]:
            ok, m, lo, hi, thr = beats(j, i)
            pair.append({"arm": j, "vs": i, "mean_diff": m, "boot95_lo": lo, "boot95_hi": hi, "threshold": thr, "beats": ok})
    L += ["## Paired differences (arm minus simpler arm, nats/game)", "", md(pd.DataFrame(pair).set_index(["arm", "vs"]), ".5f"), ""]
    ranked = sorted(ORDER, key=lambda a: -pm[a].mean())
    winner = None
    for a in ranked:
        if all(beats(a, i)[0] for i in ORDER[:ORDER.index(a)]):
            winner = a
            break
    L += ["## Decision", "", f"Ranking by fold-2 mean log score: {', '.join(f'{a} ({pm[a].mean():.5f})' for a in ranked)}.", "",
          f"**Winner under the pre-registered rule: {winner}** (best-ranked arm that beats every simpler arm by a 95% bootstrap interval excluding 0 and more than max(seed SD, 0.001); ties go to the simpler arm).", ""]
    (RES / "winner.json").write_text(json.dumps({"winner": winner, "hash": byarm[winner]}))

    # ---- secondary metrics
    cells = pd.DataFrame({"actual": np.bincount(tot_a, minlength=11) / n, **{a: sec[byarm[a]]["tp"].mean(0) for a in ORDER}}, index=[f"k={k}" if k < 10 else "k=10+" for k in TOTK])
    for a in ORDER:
        cells[f"{a}_dpp"] = (cells[a] - cells["actual"]) * 100
    L += ["## G5 cells: P(total = k), fold 2 (dpp = sim minus actual in percentage points; tolerance 1.0)", "", md(cells, ".4f"), ""]
    sd = []
    for a in ORDER:
        P = sec[byarm[a]]["P"]
        sd.append({"arm": a, "total_SD_ratio": P["total_sd"] / act["total_sd"], "total: SD of game means": P["total_sd_means"], "total: mean within-game SD": P["total_sd_within"],
                   "margin_SD_ratio": P["margin_sd"] / act["margin_sd"], "margin: SD of game means": P["margin_sd_means"], "margin: mean within-game SD": P["margin_sd_within"],
                   "corr": P["corr"], "corr_diff": P["corr"] - act["corr"], "total_bias": P["total_mean"] - act["total_mean"], "margin_bias": P["margin_mean"] - act["margin_mean"],
                   "reg_tie_diff_pp": (sec[byarm[a]]["reg_tie"] - act["reg_tie"]) * 100})
    L += ["## Dispersion, correlation, bias, regulation-tie (accuracy = SD of per-game means; dispersion = mean within-game SD)", "", md(pd.DataFrame(sd).set_index("arm"), ".4f"), "",
          f"Actual: total SD {act['total_sd']:.4f}, margin SD {act['margin_sd']:.4f}, corr {act['corr']:.4f}.", ""]

    # ML calibration by decile (winner)
    pw = arms[byarm[winner]]["pwin"]
    dec = pd.qcut(pw, 10, labels=False, duplicates="drop")
    cal = pd.DataFrame({"pred": pw, "act": g.home_win.to_numpy().astype(float), "d": dec}).groupby("d").agg(n=("pred", "size"), pred=("pred", "mean"), actual=("act", "mean"))
    L += [f"## ML calibration by predicted decile ({winner}; includes OT/SO resolution)", "", md(cal, ".4f"), ""]

    # segments (primary metric)
    nh = g.copy()
    fav = np.abs(arms[byarm[winner]]["lam_h"] - arms[byarm[winner]]["lam_a"])
    seg = {}
    seg["month"] = g.date.str[:7].to_numpy()
    seg["favourite band (|pred margin| tercile of winner)"] = pd.qcut(fav, 3, labels=["T1 close", "T2", "T3 big fav"]).astype(str)
    seg["game type"] = np.where(g.gtype.to_numpy() == 3, "PO (n=%d, UNDERPOWERED<300)" % (g.gtype == 3).sum(), "RS")
    seg["goalie quintile (home log-odds z: opposing goalie weakness)"] = pd.qcut(g.z_h.to_numpy(), 5, labels=False).astype(str)
    for name, key in seg.items():
        tab = pd.DataFrame({a: pd.Series(pm[a]).groupby(key).mean() for a in ORDER})
        tab["n"] = pd.Series(np.ones(n)).groupby(key).sum()
        L += [f"## Mean log score by {name}", "", md(tab, ".4f"), ""]
    ha = {}
    for a in ORDER:
        F = arms[byarm[a]]["final"].astype(np.float64)
        ph, pa = marg(F)
        ha[a] = {"home goals": np.log(np.maximum(ph[np.arange(n), np.minimum(hg, E.N - 1)], 1e-12)).mean(),
                 "away goals": np.log(np.maximum(pa[np.arange(n), np.minimum(ag, E.N - 1)], 1e-12)).mean()}
    L += ["## Marginal log score by side (home / away)", "", md(pd.DataFrame(ha).T, ".4f"), ""]

    # responsiveness: expected team goals by as-of team-rating quintile
    resp = []
    for a in ORDER:
        F = arms[byarm[a]]["final"].astype(np.float64)
        mh, ma, *_ = moments(F)
        net = np.r_[arms[byarm[a]]["net_h"], arms[byarm[a]]["net_a"]]
        pred = np.r_[mh, ma]
        actg = np.r_[hg, ag]
        q = pd.qcut(net, 5, labels=False)
        t = pd.DataFrame({"pred": pred, "act": actg, "q": q}).groupby("q").mean()
        slope = np.polyfit(pred, actg, 1)[0]
        resp.append({"arm": a, **{f"Q{int(i)+1} pred/act": f"{r.pred:.3f}/{r.act:.3f}" for i, r in t.iterrows()}, "slope(actual on pred)": slope})
    L += ["## Responsiveness: expected vs actual goals by as-of team net-rating quintile (Q1 weakest)", "", md(pd.DataFrame(resp).set_index("arm"), ".3f"), ""]

    Path(args.out).write_text("\n".join(L) + "\n", encoding="utf-8")
    pass
    print("winner", winner)


if __name__ == "__main__":
    main()
