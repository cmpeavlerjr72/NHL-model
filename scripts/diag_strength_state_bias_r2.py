"""SS-R2 pre-registered bias checks (docs/models/strength_state/experiments.md SS-R2), on fold 2 (2024-25), for every
hazard arm H0'-H3', from the frozen fold-2 predictions (real path):

1. Season level: predicted / actual penalty-taking events per team-game, overall (pass |ratio - 1| <= 3%) and by
   calendar month of the game date (pass |ratio - 1| <= 8% in every month with n >= 100 games; smaller months are
   UNDERPOWERED).
2. State 'other': the share of fold-2 events in state 'other' (goalie pulled, no delayed-penalty signal) after change
   1, and the sim-vs-real shortfall attributable to it (pass <= 1.5%). The sim never visits 'other'; it spends that
   clock time in the non-pulled state. Net shortfall = (actual events in 'other' rows - the arm's expected events on
   the same rows re-labelled 5v5) / all actual events. The re-labelling to 5v5 is an approximation (the replayed
   penalty strength of those rows is not kept in the row table), labelled as such. The raw share is the upper bound.

    diag_strength_state_bias_r2.py [--out docs/tests/strength_state_ss_r2_bias_2026-10-15.md]
"""
import argparse
import json
import sys
from pathlib import Path

import lightgbm as lgb
import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from nhl_sim.data.load import load_games  # noqa: E402
from nhl_sim.strength_state import models_r2 as R  # noqa: E402

RES = Path("results/strength_state_r2")
ARMS = ["H0", "H1", "H2", "H3"]
TOL_ALL, TOL_MONTH, MIN_GAMES, TOL_OTHER = 0.03, 0.08, 100, 0.015


def load_model(arm):
    if arm.startswith("H3"):
        return lgb.Booster(model_file=str(RES / "models" / f"{arm}_fold2.txt"))
    return json.loads((RES / "models" / f"{arm}_fold2.json").read_text())


def predict(arm, m, r):
    return R.predict_lgb(m, r) if arm.startswith("H3") else R.predict_glm(m, r)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="docs/tests/strength_state_ss_r2_bias_2026-10-15.md")
    a = ap.parse_args()
    rows = pd.read_parquet(RES / "fold2_rows.parquet")
    rows["clock"] = (rows.t0 // 60).astype(np.int32)
    rows["cell"] = rows.st.astype(np.int64) * 10 + rows.ptype
    lab = json.loads((RES / "labels_sealed.json").read_text())
    g = load_games([20242025], columns=["game_id", "game_date_local"])
    month = pd.to_datetime(rows.game_id.map(g.set_index("game_id").game_date_local)).dt.to_period("M").astype(str)
    gmonth = pd.Series(month.to_numpy(), index=rows.game_id.to_numpy()).groupby(level=0).first()
    n_games_m = gmonth.value_counts().sort_index()
    y = rows.y.to_numpy(float)
    total = y.sum()
    other = rows.st.to_numpy() == 5
    alt = rows[other].assign(st=0, cell=lambda d: d.ptype.astype(np.int64))
    L = ["# SS-R2 pre-registered bias checks (fold 2, 2024-25; real path)", "",
         "Generated by `scripts/diag_strength_state_bias_r2.py`. Tolerances from the SS-R2 spec: season level "
         f"|pred/actual - 1| <= {TOL_ALL:.0%} overall, <= {TOL_MONTH:.0%} in every month with n >= {MIN_GAMES} games; "
         f"state-'other' shortfall <= {TOL_OTHER:.1%}.", "",
         f"Fold-2 events {int(total)}; in state 'other' after change 1: {int(y[other].sum())} "
         f"({y[other].sum() / total:.2%}); 'other' exposure {rows.exposure_s[other].sum() / 3600:.1f} team-hours.", ""]
    summ = []
    for arm in ARMS:
        mu = np.load(RES / f"fold2_haz_{lab[arm]}.npy")
        ratio = mu.sum() / total
        bym = pd.DataFrame({"pred": pd.Series(mu).groupby(month.to_numpy()).sum(),
                            "actual": pd.Series(y).groupby(month.to_numpy()).sum()})
        bym["n_games"] = n_games_m.reindex(bym.index).to_numpy()
        bym["ratio"] = bym.pred / bym.actual
        bym["status"] = np.where(bym.n_games < MIN_GAMES, "UNDERPOWERED",
                                 np.where((bym.ratio - 1).abs() <= TOL_MONTH, "PASS", "FAIL"))
        m_ok = (bym.status != "FAIL").all()
        alt_mu = predict(arm, load_model(arm), alt).sum()
        net = (y[other].sum() - alt_mu) / total
        raw = y[other].sum() / total
        s_all = "PASS" if abs(ratio - 1) <= TOL_ALL else "FAIL"
        s_oth = "PASS" if net <= TOL_OTHER else "FAIL"
        summ.append(dict(arm=arm + "'", pred=mu.sum(), actual=total, ratio=ratio, overall=s_all,
                         months_fail=int((bym.status == "FAIL").sum()), months=("PASS" if m_ok else "FAIL"),
                         other_raw_share=raw, other_net_shortfall=net, other=s_oth,
                         all_pass=(s_all == "PASS" and m_ok and s_oth == "PASS")))
        L += [f"## {arm}'", "", f"Overall predicted / actual: {mu.sum():.1f} / {int(total)} = {ratio:.4f} "
              f"({ratio - 1:+.2%}) -> **{s_all}**", "", "By month (game date):", "",
              bym.to_markdown(floatfmt=".4f"), "",
              f"State 'other': raw share {raw:.2%} (upper bound); expected events on the same rows re-labelled 5v5 "
              f"(approximation) {alt_mu:.1f}; net shortfall {net:+.2%} -> **{s_oth}**", ""]
    S = pd.DataFrame(summ).set_index("arm")
    L[6:6] = ["## Summary", "", S.to_markdown(floatfmt=".4f"), ""]
    Path(a.out).write_text("\n".join(L) + "\n", encoding="utf-8")
    S.to_csv(RES / "bias_checks.csv")
    print(S.to_string())


if __name__ == "__main__":
    main()
