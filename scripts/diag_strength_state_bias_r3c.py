"""SS-R3c bias checks + acceptance comparison (experiments.md SS-R3c). Reuses diag_strength_state_bias_r3.check
(SS-R3 thresholds: overall +/-3%, months +/-8% at n >= 100 games, 'other' net shortfall <= 1.5%; January 2025 listed).
Fold 2 gates, fold 1 diagnostic. Acceptance input: H3''c vs H3'' fold-2 LL/game (paired, game-block bootstrap 1,000;
identical v2 rows asserted); H2''c vs H2'' reported alongside.

    diag_strength_state_bias_r3c.py [--out docs/tests/strength_state_ss_r3c_bias_2026-10-15.md]
"""
import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
sys.path.insert(0, str(Path(__file__).resolve().parent))
import diag_strength_state_bias_r3 as B  # noqa: E402
from nhl_sim.strength_state.models import pois_ll  # noqa: E402

R3C = Path("results/strength_state_r3c")
R3 = Path("results/strength_state_r3")
ARMS = ["H0", "H1", "H2", "H3"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="docs/tests/strength_state_ss_r3c_bias_2026-10-15.md")
    a = ap.parse_args()
    rows = pd.read_parquet(R3C / "fold2_rows.parquet")
    old = pd.read_parquet(R3 / "fold2_rows.parquet")
    assert (rows.game_id.to_numpy() == old.game_id.to_numpy()).all() and (rows.t0.to_numpy() == old.t0.to_numpy()).all()
    lab, lab3 = json.loads((R3C / "labels_sealed.json").read_text()), json.loads((R3 / "labels_sealed.json").read_text())
    mus = {x + "''c": np.load(R3C / f"fold2_haz_{lab[x]}.npy") for x in ARMS}
    mus3 = {x + "''": np.load(R3 / f"fold2_haz_{lab3[x]}.npy") for x in ARMS}
    ms = {x + "''c": B.load_model(R3C, x, "fold2") for x in ARMS}
    ms3 = {x + "''": B.load_model(R3, x, "fold2") for x in ARMS}
    S, mt, L2 = B.check(rows, mus, ms, 20242025, "Fold 2 (2024-25), SS-R3c arms (GATES; January 2025 listed)")
    S3, _, L3 = B.check(old, mus3, ms3, 20242025, "Fold 2 (2024-25), SS-R3 arms (old level; reference)")
    games = np.sort(rows.game_id.unique())
    gpos = np.searchsorted(games, rows.game_id.to_numpy())
    idx = np.random.default_rng(20261015).integers(0, len(games), size=(1000, len(games)))
    y = rows.y.to_numpy(float)
    cmp_ = []
    for x in ARMS:
        d = (np.bincount(gpos, weights=pois_ll(y, mus[x + "''c"]), minlength=len(games))
             - np.bincount(gpos, weights=pois_ll(y, mus3[x + "''"]), minlength=len(games)))
        se = float(d[idx].mean(1).std(ddof=1))
        cmp_.append(dict(arm=x + "''c", vs=x + "''", ll_diff=float(d.mean()), se=se,
                         not_worse_2se=bool(d.mean() >= -2 * se), ll_c=float(np.bincount(
                             gpos, weights=pois_ll(y, mus[x + "''c"]), minlength=len(games)).mean())))
    T = pd.DataFrame(cmp_).set_index("arm")
    d1 = R3C / "fold1"
    r1 = pd.read_parquet(d1 / "rows.parquet")
    mus1 = {x + "''c": np.load(d1 / f"pred_{x}.npy") for x in ARMS}
    ms1 = {x + "''c": B.load_model(d1, x, "fold2") for x in ARMS}
    S1, mt1, L1 = B.check(r1, mus1, ms1, 20232024, "Fold 1 (2023-24, diagnostic), SS-R3c arms")
    par = {f: json.loads((p).read_text()) for f, p in (("fold-1 train", d1 / "parity_fold1_train.json"),
                                                        ("fold-2 train", R3C / "parity_fold2_train.json"))}
    L = ["# SS-R3c bias checks and acceptance comparison", "",
         "Generated by `scripts/diag_strength_state_bias_r3c.py` (check function from `diag_strength_state_bias_r3.py`).", ""]
    L += L2 + ["## LC-1 vs old level, fold-2 LL/game (paired, bootstrap SE)", "", T.to_markdown(floatfmt=".4f"), ""]
    L += L3 + L1
    L += ["## LC-1 per-training-season parity (in-sample predicted / actual - 1; limit 0.5%)", ""]
    for f, p in par.items():
        L += [f"- {f}: " + "; ".join(f"{k} {', '.join(f'{s} {v:+.4%}' for s, v in d.items())}" for k, d in p.items())]
    Path(a.out).write_text("\n".join(L) + "\n", encoding="utf-8")
    pd.set_option("display.width", 250)
    print(S.to_string()); print(T.to_string()); print(S1.to_string()); print(mt.to_string()); print(json.dumps(par))


if __name__ == "__main__":
    main()
